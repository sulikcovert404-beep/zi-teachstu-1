export type AgeTier = "PRE_PRIMARY" | "PRIMARY" | "MIDDLE_1" | "MIDDLE_2" | "TECHNICAL" | "GENERIC";

/** کد دورهٔ تحصیلی کتاب → سطح سن (پیش‌فرض GENERIC برای کتاب‌های بدون دوره) */
export function ageTierForLevel(level: string | null | undefined): AgeTier {
  switch (level) {
    case "PRE_PRIMARY":
      return "PRE_PRIMARY";
    case "PRIMARY":
      return "PRIMARY";
    case "MIDDLE_1":
      return "MIDDLE_1";
    case "MIDDLE_2":
      return "MIDDLE_2";
    case "TECHNICAL":
      return "TECHNICAL";
    default:
      return "GENERIC";
  }
}

