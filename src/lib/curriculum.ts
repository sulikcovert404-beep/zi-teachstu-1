/** دروسِ پایهٔ مشخص از یک دوره — پیش‌دبستانی پایه ندارد (کلاً یک فهرست). */
export function subjectsForLevelGrade(level: string | null | undefined, grade: string | null | undefined): string[] {
  if (!level) return [];
  const byLevel = SUBJECTS[level];
  if (!byLevel) return [];
  if (level === "PRE_PRIMARY") return byLevel[""] ?? [];
  if (!grade) return unionSubjectsForLevel(level);
  return byLevel[grade] ?? unionSubjectsForLevel(level);
}

/** اجتماع همهٔ دروس یک دوره (وقتی پایه انتخاب نشده). */
export function unionSubjectsForLevel(level: string | null | undefined): string[] {
  if (!level) return [];
  const byLevel = SUBJECTS[level];
  if (!byLevel) return [];
  const out: string[] = [];
  const seen = new Set<string>();
  for (const list of Object.values(byLevel)) {
    for (const s of list) {
      if (!seen.has(s)) {
        seen.add(s);
        out.push(s);
      }
    }
  }
  return out;
}

/** آیا این درس در فهرست رسمی این دوره/پایه هست؟ (برای اعتبارسنجی سرور — «سایر» همیشه آزاد است)
 *  راند ۳۰ — نام‌های قدیمی متوسطهٔ دوم (مثل «فارسی» بدون شماره یا «حسابان ۲» قدیمی)
 *  برای کتاب‌های موجود هنوز پذیرفته می‌شوند تا داده‌های قبلی خراب نشوند. */
const LEGACY_ALIASES: Record<string, string[]> = {
  MIDDLE_2: [
    "فارسی", "عربی", "دین و زندگی", "زبان انگلیسی", "حسابان ۲", "حسابان ۳",
    "ریاضی و آمار", "زمین‌شناسی", "منطق", "جامعه‌شناسی", "اقتصاد", "روان‌شناسی",
    "فلسفه", "با قرآن آشنا", "ادبیات معارف اسلامی", "تاریخ (کشورهای اسلامی)",
    "آمادگی دفاعی", "جغرافیای اجتماعی", "انسان و محیط زیست", "تاریخ",
  ],
};

export function isKnownSubject(level: string | null | undefined, grade: string | null | undefined, subject: string): boolean {
  if (subjectsForLevelGrade(level, grade).includes(subject)) return true;
  if (level && LEGACY_ALIASES[level]?.includes(subject)) return true;
  return false;
}

/** ساختار کامل برای GET /api/v1/public/meta (بات + مینی‌اپ) */
export function curriculumForMeta(): Array<{ code: string; label: string; emoji: string; grades: Array<{ grade: string; subjects: string[] }> }> {
  return EDUCATION_LEVELS.map((l) => ({
    code: l.code,
    label: l.label,
    emoji: l.emoji,
    grades:
      l.code === "PRE_PRIMARY"
        ? [{ grade: "", subjects: subjectsForLevelGrade(l.code, null) }]
        : gradesForLevel(l.code).map((g) => ({ grade: g, subjects: subjectsForLevelGrade(l.code, g) })),
  }));
}
