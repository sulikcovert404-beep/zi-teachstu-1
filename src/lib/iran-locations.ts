export const IRAN_PROVINCE_NAMES: string[] = IRAN_PROVINCES.map((p) => p.name);

export function citiesOfProvince(province: string | null | undefined): string[] {
  if (!province) return [];
  const p = IRAN_PROVINCES.find((x) => x.name === province.trim());
  return p?.cities ?? [];
}

export function isValidProvince(province: string | null | undefined): boolean {
  return !!province && IRAN_PROVINCE_NAMES.includes(province.trim());
}

export function isValidCity(province: string | null | undefined, city: string | null | undefined): boolean {
  if (!province || !city) return false;
  return citiesOfProvince(province).includes(city.trim());
}

// مناطقٔ آموزشی: تهران ۲۲ منطقهٔ شهرداری (آموزش‌وپرورش مناطق ۱..۲۲ را نگه می‌دارد)؛
// مراکز استان بزرگ معمولاً تا ۸ منطقه دارند؛ سایر شهرها منطقهٔ مرکزی + چند منطقه.
export function districtsOfCity(province: string | null | undefined, city: string | null | undefined): string[] {
  const cleanCity = city?.trim();
  if (!cleanCity) return [];
  if (cleanCity === "تهران") {
    return Array.from({ length: 22 }, (_, i) => `منطقهٔ ${fa(i + 1)}`);
  }
  if (cleanCity === "مشهد" || cleanCity === "اصفهان" || cleanCity === "کرج") {
    return Array.from({ length: 12 }, (_, i) => `منطقهٔ ${fa(i + 1)}`);
  }
  if (cleanCity === "شیراز" || cleanCity === "تبریز" || cleanCity === "اهواز" || cleanCity === "قم" || cleanCity === "یزد") {
    return Array.from({ length: 9 }, (_, i) => `منطقهٔ ${fa(i + 1)}`);
  }
  // مرکز استان‌ها و شهرهای بزرگ‌تر: تا ۶ منطقه
  const isCapital = IRAN_PROVINCES.some((p) => p.name !== "تهران" && p.cities[0] === cleanCity);
  if (isCapital) {
    return Array.from({ length: 6 }, (_, i) => `منطقهٔ ${fa(i + 1)}`);
  }
  return ["منطقهٔ مرکزی", "منطقهٔ ۱", "منطقهٔ ۲", "منطقهٔ ۳"];
}

const FA_DIGITS = "۰۱۲۳۴۵۶۷۸۹";
function fa(n: number): string {
  return String(n)
    .split("")
    .map((d) => FA_DIGITS[Number(d)] ?? d)
    .join("");
}

export function isValidDistrict(province: string | null | undefined, city: string | null | undefined, district: string | null | undefined): boolean {
  if (!district) return false;
  return districtsOfCity(province, city).includes(district.trim());
}
